def visual_debug_unet(num_samples=3):
    test_img_dir = os.path.join(DATASET_ROOT, 'test', 'images')
    test_lbl_dir = os.path.join(DATASET_ROOT, 'test', 'labels')

    img_files = glob.glob(os.path.join(test_img_dir, '*.*'))
    if not img_files:
        print("❌ Test 이미지가 없습니다.")
        return

    samples = random.sample(img_files, min(num_samples, len(img_files)))

    print(f"📸 U-Net Visual Debugging 시작")
    print("-" * 60)

    for i, img_path in enumerate(samples):
        file_name = os.path.splitext(os.path.basename(img_path))[0]
        lbl_path = os.path.join(test_lbl_dir, file_name + '.txt')

        # 1. 이미지 로드 (OpenCV)
        origin_img = cv2.imread(img_path)
        origin_img = cv2.cvtColor(origin_img, cv2.COLOR_BGR2RGB)
        h, w, _ = origin_img.shape

        # ---------------------------------------------------------
        # [Left] Ground Truth 시각화 (YOLO 코드 방식 유지)
        # ---------------------------------------------------------
        gt_img = origin_img.copy()
        gt_polys, gt_names = get_ground_truth_polygon(lbl_path, origin_img.shape, class_names)

        for pts, label in zip(gt_polys, gt_names):
            # 정답은 초록색 계열
            color = (0, 255, 0)
            cv2.polylines(gt_img, [pts], True, color, 2)

            # 내부 살짝 색칠
            overlay = gt_img.copy()
            cv2.fillPoly(overlay, [pts], color)
            cv2.addWeighted(overlay, 0.3, gt_img, 0.7, 0, gt_img)

            # 라벨 텍스트
            if len(pts) > 0:
                cv2.putText(gt_img, label, (pts[0][0][0], pts[0][0][1]-5),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 2)

        # ---------------------------------------------------------
        # [Right] U-Net Prediction 시각화
        # ---------------------------------------------------------
        pred_img = origin_img.copy()

        if model:
            # A. 전처리 (Resize -> Normalize -> Tensor)
            transformed = val_transform(image=origin_img)['image'].unsqueeze(0).to(device)

            # B. 추론
            with torch.no_grad():
                output = model(transformed)
                # (1, C, 512, 512) -> (512, 512) : 가장 높은 확률 클래스 선택
                pred_mask = torch.argmax(output, dim=1).squeeze().cpu().numpy()

            # C. 마스크를 원본 크기로 복원 (512 -> Original H, W)
            # interpolation=cv2.INTER_NEAREST 필수 (클래스 ID 유지를 위해)
            pred_mask_resized = cv2.resize(pred_mask.astype('uint8'), (w, h), interpolation=cv2.INTER_NEAREST)

            # D. 예측 마스크 오버레이 (Overlay)
            colored_mask = np.zeros_like(pred_img)

            # 배경(0)을 제외한 클래스만 색칠
            unique_classes = np.unique(pred_mask_resized)
            detected_labels = []

            for cls_id in unique_classes:
                if cls_id == 0: continue # 배경 제외

                # 해당 클래스 마스크 추출
                class_mask = (pred_mask_resized == cls_id).astype('uint8') * 255

                # 색상 지정
                color = colors[cls_id].tolist()

                # 마스크 영역에 색상 입히기
                colored_mask[pred_mask_resized == cls_id] = color

                # (옵션) 외곽선 그리기 - YOLO 스타일처럼 보이게
                contours, _ = cv2.findContours(class_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
                cv2.drawContours(pred_img, contours, -1, color, 2)

                # (옵션) 텍스트 표시 (가장 큰 덩어리 중심에)
                if len(contours) > 0:
                    largest_contour = max(contours, key=cv2.contourArea)
                    M = cv2.moments(largest_contour)
                    if M["m00"] != 0:
                        cX = int(M["m10"] / M["m00"])
                        cY = int(M["m01"] / M["m00"])
                        label_name = class_names[cls_id - 1] if (cls_id - 1) < len(class_names) else f"Class {cls_id}"
                        detected_labels.append(label_name)
                        cv2.putText(pred_img, label_name, (cX, cY),
                                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 2)

            # 이미지 합치기 (원본 + 컬러 마스크)
            cv2.addWeighted(colored_mask, 0.4, pred_img, 0.6, 0, pred_img)

        # ---------------------------------------------------------
        # 시각화 출력
        # ---------------------------------------------------------
        fig, axes = plt.subplots(1, 2, figsize=(18, 9))

        axes[0].imshow(gt_img)
        axes[0].set_title(f"[Ground Truth] Labels (Polygon)\n(File: {file_name})", fontsize=14, fontweight='bold', color='green')
        axes[0].axis('off')

        axes[1].imshow(pred_img)
        axes[1].set_title(f"[U-Net Prediction] Segmentation Mask", fontsize=14, fontweight='bold', color='blue')
        axes[1].axis('off')

        plt.tight_layout()
        plt.show()
        print(f"✅ Sample {i+1} 완료.")

