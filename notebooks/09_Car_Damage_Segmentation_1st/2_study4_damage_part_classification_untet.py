def evaluate_unet_performance(model, dataloader, n_classes, device):
    model.eval()

    # 지표 변수
    iou_scores = []
    total_time = 0
    total_frames = 0

    print(f"🚀 성능 평가 시작 (총 {len(dataloader.dataset)}장)...")

    # Warm-up (GPU 예열)
    dummy = torch.randn(1, 3, 512, 512).to(device)
    for _ in range(5):
        _ = model(dummy)

    with torch.no_grad():
        for images, masks in tqdm(dataloader, desc="Evaluating"):
            images = images.to(device)
            # Flatten: mIoU 계산을 위해 1차원 배열로 펼침
            masks_np = masks.cpu().numpy().flatten()

            # 시간 측정 (Start)
            start_time = time.time()

            outputs = model(images)
            preds = torch.argmax(outputs, dim=1)

            # 시간 측정 (End)
            if device == 'cuda': torch.cuda.synchronize() # GPU 동기화 (정확한 시간 측정용)
            end_time = time.time()

            # 속도 누적
            total_time += (end_time - start_time)
            total_frames += images.size(0)

            # mIoU 계산 (Batch 단위)
            preds_np = preds.cpu().numpy().flatten()

            # micro: 전체 픽셀 합산 평균, macro: 클래스별 평균 (macro가 더 엄격함)
            # labels: 존재하는 클래스만 계산하거나 전체 클래스 지정
            current_iou = jaccard_score(masks_np, preds_np, average='macro', labels=list(range(n_classes)))
            iou_scores.append(current_iou)

