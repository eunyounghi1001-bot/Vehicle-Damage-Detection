# 정답은 .txt 파일(Polygon)을 읽어서 그리는 것이 가장 정확하므로 님의 코드를 그대로 씁니다.
def get_ground_truth_polygon(lbl_path, img_shape, class_names):
    h, w = img_shape[:2]
    gt_polygons = []
    gt_labels = []

    if os.path.exists(lbl_path):
        with open(lbl_path, 'r') as f:
            for line in f:
                parts = list(map(float, line.strip().split()))
                cls_id = int(parts[0])
                coords = parts[1:]

                # 좌표 복원
                pts = []
                for i in range(0, len(coords), 2):
                    pts.append([int(coords[i] * w), int(coords[i+1] * h)])
                pts = np.array(pts, np.int32).reshape((-1, 1, 2))

                gt_polygons.append(pts)
                name = class_names[cls_id] if cls_id < len(class_names) else str(cls_id)
                gt_labels.append(name)

    return gt_polygons, gt_labels

