"""# Step 3. 데이터셋 클래스 및 로더 정의
 - PyTorch 학습을 위한 Custom Dataset을 정의합니다. U-Net은 입력 이미지 크기가 고정되어야 하므로 리사이징(Resizing)이 필수입니다.
"""

from torch.utils.data import Dataset, DataLoader
import albumentations as A
from albumentations.pytorch import ToTensorV2

class CarPartDataset(Dataset):
    def __init__(self, root_dir, split='train', transform=None):
        self.img_dir = os.path.join(root_dir, split, 'images')
        self.mask_dir = os.path.join(root_dir, split, 'masks')
        self.img_ids = [os.path.basename(f) for f in glob(os.path.join(self.img_dir, '*.*'))]
        self.transform = transform

    def __len__(self):
        return len(self.img_ids)

    def __getitem__(self, idx):
        img_name = self.img_ids[idx]
        img_path = os.path.join(self.img_dir, img_name)
        mask_name = img_name.rsplit('.', 1)[0] + '.png'
        mask_path = os.path.join(self.mask_dir, mask_name)

        image = cv2.imread(img_path)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)

        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented['image']
            mask = augmented['mask']

        # 마스크는 long 타입이어야 함 (CrossEntropy용)
        return image, mask.long()

# 전처리 파이프라인 (512x512 리사이징 권장)
