# 2-2. Polygon(.txt)을 Mask(.png)로 변환하는 함수
def create_masks(data_root):
    print("🔄 YOLO Polygon 라벨을 U-Net용 마스크 이미지로 변환합니다...")

    # 클래스 정보 로드 (없으면 기본값 설정 필요)
    # Background는 0번, 나머지 클래스는 1번부터 시작하도록 매핑

    for split in ['train', 'val', 'test']:
        img_dir = os.path.join(data_root, split, 'images')
        lbl_dir = os.path.join(data_root, split, 'labels')
        mask_dir = os.path.join(data_root, split, 'masks') # 마스크 저장 경로

        os.makedirs(mask_dir, exist_ok=True)

        img_files = glob(os.path.join(img_dir, '*.*'))

        for img_path in tqdm(img_files, desc=f"{split} converting"):
            # 이미지 크기 확인
            img = cv2.imread(img_path)
            if img is None: continue
            h, w = img.shape[:2]

            # 빈 마스크 생성 (0=배경)
            mask = np.zeros((h, w), dtype=np.uint8)

            # 라벨 파일 읽기
            basename = os.path.basename(img_path).rsplit('.', 1)[0]
            txt_path = os.path.join(lbl_dir, basename + '.txt')

            if os.path.exists(txt_path):
                with open(txt_path, 'r') as f:
                    lines = f.readlines()

                for line in lines:
                    parts = line.strip().split()
                    cls_id = int(parts[0])

                    # 좌표 파싱 및 복원
                    coords = np.array([float(x) for x in parts[1:]]).reshape(-1, 2)
                    coords[:, 0] *= w
                    coords[:, 1] *= h
                    coords = coords.astype(np.int32)

                    # 마스크 그리기 (클래스 ID + 1 값을 픽셀 값으로 사용)
                    # 예: YOLO Class 0 -> Mask Value 1 (배경 0과 구분)
                    cv2.fillPoly(mask, [coords], cls_id + 1)

            # 마스크 저장 (PNG)
            cv2.imwrite(os.path.join(mask_dir, basename + '.png'), mask)

