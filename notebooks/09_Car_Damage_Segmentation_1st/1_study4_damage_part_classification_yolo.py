def calculate_semantic_miou(model_path, img_dir, label_dir):
    print(f"🚀 mIoU 계산 시작 (Model: {os.path.basename(model_path)})")

    model = YOLO(model_path)
    class_names = model.names
    num_classes = len(class_names)

    img_files = glob.glob(os.path.join(img_dir, '*.jpg')) + glob.glob(os.path.join(img_dir, '*.png'))
    img_files.sort()

    # 클래스별 IoU를 저장할 리스트
    # intersection_sum[class_id], union_sum[class_id]
    total_intersection = np.zeros(num_classes)
    total_union = np.zeros(num_classes)

    print(f"📂 총 {len(img_files)}장 이미지 분석 중...")

    for img_path in tqdm(img_files):
        # 1. 이미지 정보 읽기 (크기 필요)
        img = cv2.imread(img_path)
        if img is None: continue
        h, w = img.shape[:2]

        # 2. 라벨 파일 경로 찾기
        base_name = os.path.basename(img_path).rsplit('.', 1)[0]
        label_path = os.path.join(label_dir, base_name + '.txt')

        # 3. 모델 추론
        results = model.predict(img_path, conf=0.25, verbose=False, device=0 if torch.cuda.is_available() else 'cpu')
        result = results[0]

        # --- 클래스별로 반복하며 IoU 계산 ---
        for cls_id in range(num_classes):
            # A. Ground Truth Mask 생성 (Semantic: 모든 객체 합침)
            gt_mask = polygon_to_mask(label_path, (h, w), cls_id)

            # B. Prediction Mask 생성
            pred_mask = np.zeros((h, w), dtype=np.uint8)

            if result.masks is not None:
                # 현재 클래스에 해당하는 예측 마스크만 추출
                # result.boxes.cls는 감지된 객체들의 클래스 ID 리스트
                pred_cls_ids = result.boxes.cls.cpu().numpy().astype(int)

                # 마스크 데이터 (이미지 크기로 resize 필요할 수 있음. orig_shape 사용)
                # ultralytics의 masks.data는 GPU 텐서일 수 있음
                if hasattr(result.masks, 'data'):
                    # 마스크가 있는 경우
                    for i, det_cls in enumerate(pred_cls_ids):
                        if det_cls == cls_id:
                            # 개별 마스크 추출 및 리사이즈
                            # masks.data는 (N, H, W) 형태이나 원본 크기가 아닐 수 있음 -> scale_image 자동 처리됨?
                            # 안전하게 result.masks.xy (폴리곤 좌표)를 사용하여 다시 그리는 게 정확함

                            # 방식 1: 폴리곤 좌표로 다시 그리기 (가장 안전)
                            poly = result.masks.xy[i].astype(np.int32)
                            cv2.fillPoly(pred_mask, [poly], 1)

            # C. Intersection & Union 계산
            # flatten()으로 1차원 배열로 만든 뒤 계산
            inter = np.logical_and(gt_mask, pred_mask).sum()
            union = np.logical_or(gt_mask, pred_mask).sum()

            total_intersection[cls_id] += inter
            total_union[cls_id] += union

    # --- 최종 mIoU 계산 ---
    print("\n" + "="*50)
    print("📊 YOLO Segmentation -> Semantic mIoU 변환 결과")
    print("="*50)
    print(f"{'Class Name':<20} {'IoU':<10}")
    print("-" * 30)

    iou_list = []
    for cls_id in range(num_classes):
        if total_union[cls_id] == 0:
            iou = 0.0 # 정답도 없고 예측도 없었으면 0 (또는 데이터셋에 따라 NaN 처리)
            # 보통 정답이 아예 없는 클래스는 mIoU 평균에서 제외하기도 함
            print(f"{class_names[cls_id]:<20} {'N/A (No GT)':<10}")
            continue

        iou = total_intersection[cls_id] / total_union[cls_id]
        iou_list.append(iou)
        print(f"{class_names[cls_id]:<20} {iou:.4f}")

    miou = np.mean(iou_list) if iou_list else 0
    print("-" * 30)
    print(f"🏆 Final mIoU: {miou:.4f}")
    print("="*50)

    return miou

