# 2. 유틸리티 함수: 폴리곤 -> 바이너리 마스크 변환
# ==========================================
def polygon_to_mask(label_path, img_shape, class_id_target):
    """
    YOLO 라벨(.txt)을 읽어 특정 클래스에 대한 Binary Mask(0 or 1)를 생성합니다.
    Semantic Segmentation 비교를 위해 개별 객체를 구분하지 않고 모두 1로 합칩니다.
    """
    h, w = img_shape[:2]
    mask = np.zeros((h, w), dtype=np.uint8)

    if not os.path.exists(label_path):
        return mask

    with open(label_path, 'r') as f:
        lines = f.readlines()

    for line in lines:
        parts = line.strip().split()
        if len(parts) < 3: continue

        # 클래스 확인
        cls_id = int(parts[0]) if parts[0].isdigit() else -1

        # 해당 클래스만 마스크에 그림
        if cls_id == class_id_target:
            # 좌표 정규화 해제 (0~1 -> 0~w, 0~h)
            coords = np.array([float(x) for x in parts[1:]]).reshape(-1, 2)
            coords[:, 0] *= w
            coords[:, 1] *= h
            coords = coords.astype(np.int32)

            # 폴리곤 내부 채우기 (1로 설정)
            cv2.fillPoly(mask, [coords], 1)

    return mask

