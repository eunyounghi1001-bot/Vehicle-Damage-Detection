# 2. Polygon 시각화 검증 (클래스명 표시 수정 & 투명도 50%)
def visualize_polygon_sample(root_dir, split='train', num_samples=6):
    img_dir = os.path.join(root_dir, split, 'images')
    lbl_dir = os.path.join(root_dir, split, 'labels')

    # 1. 클래스 리스트 직접 정의 (파일 읽기 오류 방지)
    class_names = [
        "Front fender(L)", "Rear bumper", "Front Wheel(R)", "Trunk lid", "Rocker panel(L)",
        "Front fender(R)", "Front bumper", "Bonnet", "Rear Wheel(R)", "Rear door(R)",
        "Front door(R)", "Head lights(R)", "Rear fender(R)", "Rear fender(L)", "Rocker panel(R)",
        "Rear lamp(L)", "Side mirror(R)", "Rear Wheel(L)", "Rear door(L)", "Side mirror(L)",
        "Head lights(L)", "Front Wheel(L)", "Front door(L)", "Rear lamp(R)", "Windshield",
        "Roof", "Undercarriage", "Rear windshield", "C pillar(L)", "A pillar(L)",
        "C pillar(R)", "A pillar(R)"
    ]

    # 이미지 파일 리스트
    img_files = glob.glob(os.path.join(img_dir, '*.*'))
    if not img_files:
        print("❌ 이미지를 찾을 수 없습니다.")
        return

    # 샘플 랜덤 추출
    num_samples = min(num_samples, len(img_files))
    samples = random.sample(img_files, num_samples)

    plt.figure(figsize=(15, 10))

    for i, img_path in enumerate(samples):
        # 이미지 로드
        img = cv2.imread(img_path)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
        h, w, _ = img.shape

        # 라벨 로드
        basename = os.path.splitext(os.path.basename(img_path))[0]
        lbl_path = os.path.join(lbl_dir, basename + '.txt')

        if os.path.exists(lbl_path):
            with open(lbl_path, 'r') as f:
                lines = f.readlines()

            for line in lines:
                parts = list(map(float, line.strip().split()))
                cls_id = int(parts[0])
                coords = parts[1:]

                # Polygon 좌표 복원
                points = []
                for j in range(0, len(coords), 2):
                    px = int(coords[j] * w)
                    py = int(coords[j+1] * h)
                    points.append([px, py])

                points = np.array(points, np.int32)
                points = points.reshape((-1, 1, 2))

                # 색상 설정
                color = plt.cm.tab10(cls_id % 10)
                color = tuple(int(c*255) for c in color[:3])

                # --- 투명도 50% 적용 ---
                overlay = img.copy()
                cv2.fillPoly(overlay, [points], color=color, lineType=cv2.LINE_AA)
                cv2.addWeighted(overlay, 0.5, img, 0.5, 0, img)
                cv2.polylines(img, [points], True, color, 2) # 외곽선
                # ---------------------

                # 텍스트 표시 수정: "클래스명 (ID)"
                if 0 <= cls_id < len(class_names):
                    name = class_names[cls_id]
                    label_text = f"{name} ({cls_id})"
                else:
                    label_text = f"ID: {cls_id}"

                # 텍스트 배경 (가독성 향상)
                text_size, _ = cv2.getTextSize(label_text, cv2.FONT_HERSHEY_SIMPLEX, 0.5, 1)
                text_x, text_y = points[0][0][0], points[0][0][1] - 10
                cv2.rectangle(img, (text_x, text_y - text_size[1] - 5), (text_x + text_size[0], text_y + 5), color, -1)

                # 텍스트 쓰기
                cv2.putText(img, label_text, (text_x, text_y),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1, cv2.LINE_AA)

        plt.subplot(2, 3, i+1)
        plt.imshow(img)
        plt.axis('off')
        plt.title(basename, fontsize=10)

    plt.tight_layout()
    plt.show()

# 실행
