"""## 2-2. segmentation 학습"""

import cv2
import numpy as np
import matplotlib.pyplot as plt
import os
import random
import glob

# 1. 설정: 데이터셋 경로
DATASET_ROOT = '/content/dataset/balanced_dataset_split_polygon'
classes_list = [
    "Front fender(L)", "Rear bumper", "Front Wheel(R)", "Trunk lid", "Rocker panel(L)",
    "Front fender(R)", "Front bumper", "Bonnet", "Rear Wheel(R)", "Rear door(R)",
    "Front door(R)", "Head lights(R)", "Rear fender(R)", "Rear fender(L)", "Rocker panel(R)",
    "Rear lamp(L)", "Side mirror(R)", "Rear Wheel(L)", "Rear door(L)", "Side mirror(L)",
    "Head lights(L)", "Front Wheel(L)", "Front door(L)", "Rear lamp(R)", "Windshield",
    "Roof", "Undercarriage", "Rear windshield", "C pillar(L)", "A pillar(L)",
    "C pillar(R)", "A pillar(R)"
]

# 2. 샘플 이미지 및 라벨 로드 함수
def get_random_sample(root_dir, split='train'):
    img_dir = os.path.join(root_dir, split, 'images')
    lbl_dir = os.path.join(root_dir, split, 'labels')

    img_files = glob.glob(os.path.join(img_dir, '*.*'))
    if not img_files:
        raise FileNotFoundError(f"이미지를 찾을 수 없습니다: {img_dir}")

    # 랜덤 선택
    img_path = random.choice(img_files)
    file_name = os.path.splitext(os.path.basename(img_path))[0]
    lbl_path = os.path.join(lbl_dir, file_name + '.txt')

    return img_path, lbl_path

# 3. 데이터 파싱 및 시각화 준비
img_path, lbl_path = get_random_sample(DATASET_ROOT, split='train')

# 이미지 로드
img = cv2.imread(img_path)
img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
h, w, c = img.shape

# 라벨 파싱
polygons = [] # 다각형 좌표 리스트
bboxes = []   # 바운딩 박스 리스트
class_ids = []

if os.path.exists(lbl_path):
    with open(lbl_path, 'r') as f:
        lines = f.readlines()
        for line in lines:
            parts = list(map(float, line.strip().split()))
            cls_id = int(parts[0])
            coords = parts[1:]

            # 정규화된 좌표(0~1)를 픽셀 좌표(px)로 변환
            pts = []
            for i in range(0, len(coords), 2):
                px = int(coords[i] * w)
                py = int(coords[i+1] * h)
                pts.append([px, py])

            pts = np.array(pts, np.int32)
            polygons.append(pts)
            class_ids.append(cls_id)

            # Polygon에서 Bounding Box 추출 (min x, min y, max x, max y)
            x_min, y_min = np.min(pts, axis=0)
            x_max, y_max = np.max(pts, axis=0)
            bboxes.append([x_min, y_min, x_max, y_max])

# 4. 시각화 생성 (4가지 관점)

# [View 1] Vector Visualization (Polygon + BBox)
vis_vector = img.copy()
for pts, box, cid in zip(polygons, bboxes, class_ids):
    # Polygon 그리기 (선)
    cv2.polylines(vis_vector, [pts], isClosed=True, color=(0, 255, 0), thickness=2)
    # Bounding Box 그리기 (점선 흉내)
    cv2.rectangle(vis_vector, (box[0], box[1]), (box[2], box[3]), (255, 0, 0), 1)
    # 텍스트
    cv2.putText(vis_vector, classes_list[cid], (box[0], box[1]-5),
                cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 2)

# [View 2] Binary Mask (Machine's View)
# 검은 배경에 흰색으로 채워진 영역 (학습의 정답지)
mask_img = np.zeros((h, w), dtype=np.uint8)
for pts in polygons:
    cv2.fillPoly(mask_img, [pts], 255)

# [View 3] Instance Overlay (Final Goal)
vis_overlay = img.copy()
for pts, cid in zip(polygons, class_ids):
    # 색상 랜덤 생성
    color = np.random.randint(0, 255, (3,), dtype=np.uint8).tolist()

    # 1. 마스크 영역 생성
    overlay = vis_overlay.copy()
    cv2.fillPoly(overlay, [pts], color)

    # 2. 원본과 블렌딩 (투명도 0.5)
    cv2.addWeighted(overlay, 0.5, vis_overlay, 0.5, 0, vis_overlay)

    # 3. 외곽선 강조
    cv2.polylines(vis_overlay, [pts], True, color, 2)

# 5. Plotting
fig, axes = plt.subplots(1, 4, figsize=(24, 6))
titles = ["1. Original Image", "2. Vector Label (Point & Box)", "3. Binary Mask (Machine View)", "4. Instance Overlay"]
images = [img, vis_vector, mask_img, vis_overlay]

for ax, img_show, title in zip(axes, images, titles):
    if len(img_show.shape) == 2: # Gray scale (Mask)
        ax.imshow(img_show, cmap='gray')
    else:
        ax.imshow(img_show)
    ax.set_title(title, fontsize=14, fontweight='bold')
    ax.axis('off')

plt.suptitle(f"Segmentation Theory: From Coordinates to Pixels\nFile: {os.path.basename(img_path)}", fontsize=16)
plt.tight_layout()
plt.show()

"""## ※ Segmentation 기초 학습: Polygon to Mask
 1. Original: 원본 이미지
 2. Vector (Polygon & BBox): 라벨링 툴에서 우리가 찍는 점(Point)과 이를 감싸는 박스.
    - 초록색 선이 라벨링 데이터(Polygon)
    - 파란색 박스는 Polygon의 최소/최대 좌표로 계산된 Bounding Box
    - Polygon은 오직 '차체 부위'만 감싸고 있어 Segmentation이 더 정밀한 이유
 3. Raster (Binary Mask): (핵심) 점들이 연결되어 만들어진 '면적'. 컴퓨터는 이 0(배경)과 1(객체)의 픽셀 지도를 학습
    - 컴퓨터는 이미지를 숫자의 배열
    - Segmentation 모델(YOLOv8-seg)은 최종적으로 이 흑백 이미지(Mask)를 정답지로 삼아, 입력 이미지를 보며 이 모양을 똑같이 그려내도록 학습
    - 이 과정에서 cv2.fillPoly 같은 함수가 좌표를 픽셀 면적으로 바꿔주는 역할
 4. Overlay: 원본 위에 마스크를 씌운 결과.
"""

import numpy as np
import matplotlib.pyplot as plt

# 1. 가상의 12x12 마스크 생성 (0으로 채워진 검은 배경)
grid_size = 12
mask = np.zeros((grid_size, grid_size), dtype=np.uint8)

# 2. 십자가 모양 그리기 (1로 채워서 객체 표시)
# (실제로는 255를 쓰지만, 여기선 보기 편하게 1로 표시)
mask[3:9, 5:7] = 1  # 세로 막대
mask[5:7, 3:9] = 1  # 가로 막대

# 3. 시각화 (이미지와 숫자를 겹쳐서 보여줌)
plt.figure(figsize=(8, 8))
plt.imshow(mask, cmap='gray') # 0은 검정, 1은 흰색으로 출력

# 각 픽셀 위에 실제 숫자(0 또는 1) 적기
for i in range(grid_size):
    for j in range(grid_size):
        value = mask[i, j]
        # 글자색: 배경이 검정이면 흰색, 배경이 흰색이면 검정색
        text_color = 'white' if value == 0 else 'black'
        plt.text(j, i, str(value), ha='center', va='center',
                 color=text_color, fontsize=12, fontweight='bold')

plt.title("Computer's View: Binary Mask is just a Matrix", fontsize=15)
plt.axis('off') # 축 숨기기
plt.tight_layout()
plt.show()

